export function localizationFor(name, englishDescription) {
  const value = pluginLocalizations[name]
  if (!value) throw new Error(`Missing localization for ${name}`)
  const chineseDescription = chineseDescriptions[name]
  if (!chineseDescription) throw new Error(`Missing Chinese description for ${name}`)
  return {
    en: { displayName: value[0], description: englishDescription },
    'zh-CN': { displayName: value[1], description: chineseDescription },
  }
}
